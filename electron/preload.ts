import { contextBridge, ipcRenderer } from 'electron';
import type { AppApi, ProgressEvent } from '../shared/types';
const api: AppApi = {
  getFortniteSettings: () => ipcRenderer.invoke('pandora:fortnite-settings'),
  previewFortniteSettings: (value, restore) => ipcRenderer.invoke('pandora:fortnite-preview', value, restore),
  changeFortniteSettings: token => ipcRenderer.invoke('pandora:fortnite-change', token),
  getActivity: () => ipcRenderer.invoke('pandora:activity'),
  previewClearActivity: () => ipcRenderer.invoke('pandora:activity-clear-preview'),
  clearActivity: token => ipcRenderer.invoke('pandora:activity-clear', token),
  getAppLifecycle: () => ipcRenderer.invoke('pandora:app-lifecycle'),
  changeAppLogin: (token, enable) => ipcRenderer.invoke('pandora:app-login-change', token, enable),
  getSystemRestore: () => ipcRenderer.invoke('pandora:system-restore'),
  previewSystemRestore: () => ipcRenderer.invoke('pandora:system-restore-preview'),
  createSystemRestore: token => ipcRenderer.invoke('pandora:system-restore-create', token),
  openSystemProtection: () => ipcRenderer.invoke('pandora:system-protection-open'),
  getGpuTelemetry: () => ipcRenderer.invoke('pandora:gpu-telemetry'),
  getStorageReliability: () => ipcRenderer.invoke('pandora:storage-reliability'),
  getPowerTuning: () => ipcRenderer.invoke('pandora:power-tuning'),
  previewPowerTuning: (id, value, restore) => ipcRenderer.invoke('pandora:power-tuning-preview', id, value, restore),
  changePowerTuning: token => ipcRenderer.invoke('pandora:power-tuning-change', token),
  getCursor: () => ipcRenderer.invoke('pandora:cursor'),
  selectCursor: bundled => ipcRenderer.invoke('pandora:cursor-select', bundled),
  changeCursor: (token, restore) => ipcRenderer.invoke('pandora:cursor-change', token, restore),
  setAppCursor: enabled => ipcRenderer.invoke('pandora:cursor-app', enabled),
  getNvidiaPreset: () => ipcRenderer.invoke('pandora:nvidia-preset'),
  saveNvidiaPreset: preset => ipcRenderer.invoke('pandora:nvidia-save', preset),
  openNvidiaControlPanel: () => ipcRenderer.invoke('pandora:nvidia-open'),
  getVisualEffects: () => ipcRenderer.invoke('pandora:visual-effects'),
  changeVisualEffect: (token, restore) => ipcRenderer.invoke('pandora:visual-change', token, restore),
  getPointer: () => ipcRenderer.invoke('pandora:pointer'),
  changePointer: (token, restore) => ipcRenderer.invoke('pandora:pointer-change', token, restore),
  inspectNetwork: () => ipcRenderer.invoke('pandora:network-inspect'),
  testDns: () => ipcRenderer.invoke('pandora:dns-test'),
  getManualGames: () => ipcRenderer.invoke('pandora:manual-games'),
  selectGameExecutable: id => ipcRenderer.invoke('pandora:game-select', id),
  clearGameExecutable: id => ipcRenderer.invoke('pandora:game-clear', id),
  previewRestoreAll: () => ipcRenderer.invoke('pandora:restore-preview'),
  restoreAll: token => ipcRenderer.invoke('pandora:restore-all', token),
  getStartupControls: () => ipcRenderer.invoke('pandora:startup-controls'),
  changeStartup: (token, restore) => ipcRenderer.invoke('pandora:startup-change', token, restore),
  getPower: () => ipcRenderer.invoke('pandora:power'),
  applyPower: (id, expected) => ipcRenderer.invoke('pandora:power-apply', id, expected),
  restorePower: expected => ipcRenderer.invoke('pandora:power-restore', expected),
  getProfile: () => ipcRenderer.invoke('pandora:profile'),
  previewProfile: (id, custom) => ipcRenderer.invoke('pandora:profile-preview', id, custom),
  applyProfile: token => ipcRenderer.invoke('pandora:profile-apply', token),
  openWindowsSettings: page => ipcRenderer.invoke('pandora:windows-settings', page),
  testNetwork: target => ipcRenderer.invoke('pandora:network-test', target),
  getSystem: forceRefresh => ipcRenderer.invoke('pandora:system', forceRefresh),
  getMetrics: () => ipcRenderer.invoke('pandora:metrics'),
  getTweaks: () => ipcRenderer.invoke('pandora:tweaks'),
  applyTweaks: ids => ipcRenderer.invoke('pandora:apply', ids),
  revertTweaks: ids => ipcRenderer.invoke('pandora:revert', ids),
  getHistory: () => ipcRenderer.invoke('pandora:history'),
  scanCleanup: kind => ipcRenderer.invoke('pandora:scan-cleanup', kind),
  clean: (id, categories, confirmation) => ipcRenderer.invoke('pandora:clean', id, categories, confirmation),
  getProcesses: () => ipcRenderer.invoke('pandora:processes'),
  getProcessDetails: pid => ipcRenderer.invoke('pandora:process-details', pid),
  openProcessLocation: token => ipcRenderer.invoke('pandora:process-location', token),
  getOptionalApps: () => ipcRenderer.invoke('pandora:optional-apps'),
  getStartup: () => ipcRenderer.invoke('pandora:startup'),
  getGames: () => ipcRenderer.invoke('pandora:games'),
  getSettings: () => ipcRenderer.invoke('pandora:settings'),
  saveSettings: settings => ipcRenderer.invoke('pandora:save-settings', settings),
  exportReport: kind => ipcRenderer.invoke('pandora:export', kind),
  onProgress: callback => {
    const handler = (_event: Electron.IpcRendererEvent, payload: ProgressEvent) => callback(payload);
    ipcRenderer.on('pandora:progress', handler);
    return () => { ipcRenderer.removeListener('pandora:progress', handler); };
  },
  windowAction: action => ipcRenderer.send('pandora:window', action)
};
contextBridge.exposeInMainWorld('pandora', api);
